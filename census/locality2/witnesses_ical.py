"""Witness artifacts for the second locality pass, RFC 5545 SS3 corpus
(see README.md — registration pushed at main 8821bce BEFORE any entry
below was written).

Graded by `check_witnesses2.py`. Each entry names its READING, its QUOTE
(the corpus sentence, [n] = item number in
census/ical/rfc5545_s3_musts.txt, corpus-verbatim), and the artifact.

MODELING CONVENTIONS (disclosed; they bound what the mechanical checks
certify — the first study's convention 1 carries over):

1. ABSTRACT CONTENT-LINE MODEL. A prop datum is a dict {"name",
   "params": {...}, "value", "component": [enclosing component-type
   chain]}; an object datum is a nested dict {"type", "props": [...],
   "components": [...]} rooted at VCALENDAR. Values are parsed abstract
   forms (a RECUR value is a dict of rule parts; a DATE or DATE-TIME
   value carries a "vtype" and, where a witness needs arithmetic, an
   integer day index — recurrence expansion is modeled over integer day
   arithmetic, not calendar math). The mechanical checks certify
   INFORMATION FLOW, not parser implementations.

2. DENOTATION-CARRYING VALUES (item 84). An abstract UTC-OFFSET value
   carries both its encoded sign character and its signed denotation
   ({"encoded_sign", "offset_minutes"}), so encoding-vs-denotation
   consistency duties are checkable in-datum. This is the format-genre
   instance of convention 1: the abstract value is what the presentation
   grammar defines, which includes the sign character.

3. CHANNEL ATTACHMENT. "party-conduct" attaches to the application the
   sentence obliges (parser, generator, or consumer); an application's
   recognized-vocabulary set is its OWN configuration
   ("deployment-policy"); "other-artifacts" covers other iCalendar
   objects and iTIP scheduling transactions; "world-fact" covers
   leap-second history and time-zone law.

4. ANAPHORA DESIGNATIONS (registered): 143 -> VERSION, 192/193/194 ->
   RECURRENCE-ID. Each affected reading restates its designation.
"""

# --- model helpers ---------------------------------------------------------


def P(name, value, params=None, component=("VCALENDAR",)):
    return {"name": name, "value": value, "params": dict(params or {}),
            "component": list(component)}


def C(ctype, props, subs=()):
    return {"type": ctype, "props": list(props), "components": list(subs)}


def OBJ(props, subs=()):
    return C("VCALENDAR", props, subs)


def walk(comp, chain=None):
    """Yield (component-chain, prop) over a nested object."""
    chain = (chain or []) + [comp["type"]]
    for p in comp["props"]:
        yield chain, p
    for sub in comp["components"]:
        yield from walk(sub, chain)


def find_props(obj, name, ctype=None):
    return [(ch, p) for ch, p in walk(obj)
            if p["name"] == name and (ctype is None or ch[-1] == ctype)]


def ctx(desc, channel, verdict, quote):
    return {"desc": desc, "channel": channel, "verdict": verdict,
            "quote": quote}


def PAIR(item, reading, datum, c1, c2, eligible=True):
    return {"item": item, "reading": reading, "rung": "nonlocal",
            "eligible": eligible, "kind": "pair",
            "pair": {"datum_kind": "object", "datum": datum,
                     "contexts": [c1, c2]}}


def VAL(item, reading, rung, fn, accept, reject, quote, eligible=True,
        pair_fine=None):
    w = {"item": item, "reading": reading, "rung": rung,
         "eligible": eligible, "kind": "validator", "fn": fn,
         "accept": accept, "reject": reject, "quote": quote}
    if pair_fine is not None:
        w["pair_fine"] = pair_fine
    return w


def PPAIR(datum, c1, c2):
    return {"datum_kind": "prop", "datum": datum, "contexts": [c1, c2]}


