# --- validators (stable DOMAIN + the 192-194 cluster + multis) -------------


def v63(prop):
    """BYDAY numeric modifiers only under FREQ=MONTHLY/YEARLY, within one
    RECUR value."""
    if prop["name"] != "RRULE":
        return False
    r = prop["value"]
    if any(n is not None for n, _d in r.get("BYDAY", [])):
        return r.get("FREQ") in ("MONTHLY", "YEARLY")
    return True


def v84(prop):
    """Encoded sign is HYPHEN-MINUS whenever the offset denotes behind
    UTC (convention 2)."""
    if prop["name"] not in ("TZOFFSETFROM", "TZOFFSETTO"):
        return False
    v = prop["value"]
    if v["offset_minutes"] < 0:
        return v["encoded_sign"] == "-"
    return True


def v143(obj):
    """Exactly one VERSION property at calendar level (designation:
    VERSION — the adjacent item 142 carries PRODID's parallel clause)."""
    return len([p for p in obj["props"] if p["name"] == "VERSION"]) == 1


def _vtype(comp, name):
    for p in comp["props"]:
        if p["name"] == name:
            return p["value"].get("vtype")
    return None


def v192(obj):
    """Every RECURRENCE-ID's value type equals its component's DTSTART
    value type (designation: RECURRENCE-ID)."""
    ok = True
    for sub in obj["components"]:
        rid = [p for p in sub["props"] if p["name"] == "RECURRENCE-ID"]
        if rid:
            ok = ok and all(p["value"].get("vtype") == _vtype(sub, "DTSTART")
                            for p in rid)
    return ok


def _form(comp, name):
    for p in comp["props"]:
        if p["name"] == name:
            return p["value"].get("form")
    return None


def v193(obj):
    """RECURRENCE-ID is a date with local time IFF the component's
    DTSTART is (designation: RECURRENCE-ID)."""
    ok = True
    for sub in obj["components"]:
        for p in sub["props"]:
            if p["name"] == "RECURRENCE-ID":
                ok = ok and ((p["value"].get("form") == "local") ==
                             (_form(sub, "DTSTART") == "local"))
    return ok


def v194(obj):
    """When DTSTART is DATE-valued, RECURRENCE-ID's value is a calendar
    date the recurrence pattern generates (integer-day model)."""
    ok = True
    for sub in obj["components"]:
        if _vtype(sub, "DTSTART") != "DATE":
            continue
        d0 = next((p["value"]["day"] for p in sub["props"]
                   if p["name"] == "DTSTART"), None)
        rr = next((p["value"] for p in sub["props"]
                   if p["name"] == "RRULE"), None)
        for p in sub["props"]:
            if p["name"] != "RECURRENCE-ID":
                continue
            if p["value"].get("vtype") != "DATE" or rr is None:
                return False
            inst = [d0 + k * rr.get("step", 1)
                    for k in range(rr.get("COUNT", 1))]
            ok = ok and p["value"]["day"] in inst
    return ok


def v116(obj):
    """In a VTIMEZONE observance whose RRULE carries UNTIL, the UNTIL
    value equals the last onset the pattern generates from the
    observance's DTSTART (integer-day model)."""
    ok = True
    for sub in obj["components"]:
        if sub["type"] != "VTIMEZONE":
            continue
        for ob in sub["components"]:
            d0 = next((p["value"]["day"] for p in ob["props"]
                       if p["name"] == "DTSTART"), None)
            for p in ob["props"]:
                if p["name"] == "RRULE" and "UNTIL" in p["value"]:
                    inst = _instances_until(d0, p["value"]["step"],
                                            p["value"]["UNTIL"])
                    ok = ok and inst[-1] == p["value"]["UNTIL"]
    return ok


def v185(obj):
    """Where a delegate ATTENDEE (DELEGATED-FROM) and its delegator are
    co-listed in one component, the delegate's RSVP and ROLE equal the
    delegator's."""
    ok = True
    for sub in obj["components"]:
        att = {p["value"]: p for p in sub["props"]
               if p["name"] == "ATTENDEE"}
        for p in att.values():
            src = p["params"].get("DELEGATED-FROM")
            if src and src in att:
                q = att[src]
                ok = ok and (
                    p["params"].get("RSVP") == q["params"].get("RSVP")
                    and p["params"].get("ROLE") == q["params"].get("ROLE"))
    return ok


